using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Diagnostics;
using Microsoft.CodeAnalysis.Text;
using Retrocore.Isa;
using System.Text;

namespace Retrocore.Generators;

/// <summary>
///  Embeds an instruction-set description in the class its <c>RetrocoreIsaClass</c> metadata names, after
///  checking that it parses, so a malformed description fails the build at its line.
/// </summary>
/// <remarks>
///  <para>
///   <c>&lt;AdditionalFiles Include="Z80Isa.txt" RetrocoreIsaClass="Retrocore.Cpu.Z80.Z80Isa" /&gt;</c> gives
///   the static partial class <c>Z80Isa</c> an internal <c>DescriptionText</c> constant.
///  </para>
/// </remarks>
[Generator]
public sealed class IsaDescriptionGenerator : IIncrementalGenerator
{
    private const string ClassMetadata = "build_metadata.AdditionalFiles.RetrocoreIsaClass";

    private static readonly DiagnosticDescriptor s_invalid = new(
        id: "RCGEN010",
        title: "Invalid instruction-set description",
        messageFormat: "{0}",
        category: "Build",
        defaultSeverity: DiagnosticSeverity.Error,
        isEnabledByDefault: true);

    /// <summary>
    ///  Registers the description files that name a class.
    /// </summary>
    /// <param name="context">The incremental generator initialization context.</param>
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        IncrementalValuesProvider<(AdditionalText File, string Class)> files = context.AdditionalTextsProvider
            .Combine(context.AnalyzerConfigOptionsProvider)
            .Select(static (pair, _) => (pair.Left, ClassOf(pair.Right, pair.Left)))
            .Where(static pair => pair.Item2.Length != 0);

        context.RegisterSourceOutput(files, static (output, file) => Generate(output, file.File, file.Class));
    }

    private static string ClassOf(AnalyzerConfigOptionsProvider options, AdditionalText file) =>
        options.GetOptions(file).TryGetValue(ClassMetadata, out string? name) ? name.Trim() : "";

    private static void Generate(SourceProductionContext context, AdditionalText file, string fullName)
    {
        SourceText? text = file.GetText(context.CancellationToken);
        if (text is null)
        {
            context.ReportDiagnostic(Diagnostic.Create(s_invalid, Location.None, $"{file.Path} could not be read."));
            return;
        }

        string description = text.ToString();
        try
        {
            IsaParser.Parse(description);
        }
        catch (FormatException error)
        {
            context.ReportDiagnostic(Diagnostic.Create(
                s_invalid,
                LineLocation(file, text, error.Message),
                $"{Path.GetFileName(file.Path)}: {error.Message}"));

            return;
        }

        int dot = fullName.LastIndexOf('.');
        string name = dot < 0 ? fullName : fullName[(dot + 1)..];
        List<string> lines = ["// <auto-generated/>"];
        if (dot > 0) { lines.AddRange([$"namespace {fullName[..dot]};", ""]); }
        string[] body =
        [
            $"static partial class {name}",
            "{",
            "    /// <summary>",
            "    ///  The instruction-set description file's text.",
            "    /// </summary>",
            $"    internal const string DescriptionText = @\"{description.Replace("\"", "\"\"")}\";",
            "}",
            ""
        ];

        lines.AddRange(body);

        context.AddSource($"{name}.DescriptionText.g.cs", SourceText.From(string.Join("\n", lines), Encoding.UTF8));
    }

    // Parser messages start "Line n: "; point the diagnostic there.
    private static Location LineLocation(AdditionalText file, SourceText text, string message)
    {
        const string Prefix = "Line ";
        int colon = message.IndexOf(':');
        if (!message.StartsWith(Prefix, StringComparison.Ordinal)
            || colon < 0
            || !int.TryParse(message[Prefix.Length..colon], out int line)
            || line < 1
            || line > text.Lines.Count)
        {
            return Location.None;
        }

        TextSpan span = text.Lines[line - 1].Span;
        return Location.Create(file.Path, span, text.Lines.GetLinePositionSpan(span));
    }
}
