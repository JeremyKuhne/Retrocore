; .SILENTYPE's font and the routines that read it. Included by Silentype.asm.

;; Returns the columns of a glyph: five, whatever the character.
;; Out: A = 5
GLYPHWIDTH:
    lda #5
    rts

;; Reads a column of a character's glyph from the font.
;; In: CHAR = the character, GLYPHCOL = the column, 0-4
;; Out: DOTS = the column, the top dot in bit 6
;; Uses: A, Y, FONTPTR
GLYPHCOLUMN:
    lda GLYPHCOL
    asl a
    tay
    clc
    lda FONTADDR
    adc COLOFFSETS,y
    sta FONTPTR
    lda FONTADDR+1
    adc COLOFFSETS+1,y
    sta FONTPTR+1
    lda CHAR
    sec
    sbc #' '
    tay
    lda #$00
    sta XPAGE+FONTPTR+1                 ; plain addressing, no bank pair
    lda (FONTPTR),y
    sta DOTS
    rts

;; The offsets of the font's five column tables in <FONTDOTS>, by glyph column.
COLOFFSETS:
    .word 0, 96, 192, 288, 384

;; The address of <FONTDOTS>, for <GLYPHCOLUMN>.
FONTADDR:
    .word FONTDOTS

