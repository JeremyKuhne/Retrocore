;; TRS-80 MODEL III AND MODEL 4 CHARACTER GENERATORS
;;
;; The Model III and Model 4 draw text from a 2K character generator of 256 characters, eight bytes each: one per
;; scanline from the top of the cell, with bits 7-0 a row's dots from left to right. The video circuit shows the
;; first eight of a cell's scanlines from here and leaves the rest blank.
;;
;; Video RAM codes $00-$7F show the glyphs at the same place. Codes $80-$BF are block graphics the video circuit
;; draws itself, so the glyphs there serve codes $C0-$FF: those show the glyphs at $C0-$FF, or with the alternate
;; set (port $EC bit 3) those at $80-$BF.
;;
;; MODEL4P picks the chip: 0 the Model III's and Model 4's (8044316a), 1 the Model 4P's (8049007), which differs
;; only in the glyphs at $00-$1F and $C0-$FF.
;;
;; Maintained by hand. Trs80RomSourceTests check that each assembles byte-identically to its chip's dump.

.cpu Z80

.ifndef MODEL4P
MODEL4P = 0
.endif

;; Starts a character: checks that it lands at code * 8.
.macro GLYPH code
    .assert * = (code) * 8, "A GLYPH is out of order."
.endmacro

;; One row of dots: eight characters, # for a lit dot and . for a dark one.
.macro ROW dots
    .assert .strlen(dots) = 8, "A ROW has eight dots."
    .byte ((.strat(dots, 0) = '#') << 7) | ((.strat(dots, 1) = '#') << 6) | ((.strat(dots, 2) = '#') << 5) | ((.strat(dots, 3) = '#') << 4) | ((.strat(dots, 4) = '#') << 3) | ((.strat(dots, 5) = '#') << 2) | ((.strat(dots, 6) = '#') << 1) | (.strat(dots, 7) = '#')
.endmacro

