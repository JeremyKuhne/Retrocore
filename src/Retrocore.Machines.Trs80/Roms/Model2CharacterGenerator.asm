;; TRS-80 MODEL II CHARACTER GENERATOR (8043316)
;;
;; The Model II, 12 and 16 draw text from a 2K character generator of 128 characters, sixteen bytes each: one per
;; scanline from the top of the cell, with bits 7-0 a row's dots from left to right. The boot ROM sets the 6845 to
;; ten scanlines a row, and every character's last six bytes are zero. Codes $00-$1F are line-drawing and block
;; characters, and $7F is a plus-minus sign. Bit 7 of a video RAM code shows its character inverse.
;;
;; Maintained by hand. Trs80RomSourceTests check that it assembles byte-identically to the chip's dump.

.cpu Z80

;; Starts a character: fills the last one's unused scanlines and checks that it lands at code * 16.
.macro GLYPH code
    .assert * = (code) * 16 || * = (code) * 16 - 6, "A GLYPH is out of order."
    .res (code) * 16 - *, $00
.endmacro

;; One row of dots: eight characters, # for a lit dot and . for a dark one.
.macro ROW dots
    .assert .strlen(dots) = 8, "A ROW has eight dots."
    .byte ((.strat(dots, 0) = '#') << 7) | ((.strat(dots, 1) = '#') << 6) | ((.strat(dots, 2) = '#') << 5) | ((.strat(dots, 3) = '#') << 4) | ((.strat(dots, 4) = '#') << 3) | ((.strat(dots, 5) = '#') << 2) | ((.strat(dots, 6) = '#') << 1) | (.strat(dots, 7) = '#')
.endmacro

